def _autogen_context(**kw):
    opts = {
        "sqlalchemy_module_prefix": "sa.",
        "alembic_module_prefix": "op.",
        "render_item": None,
        "render_as_batch": False,
        "user_module_prefix": None,
    }
    opts.update(kw)
    migration_context = MigrationContext.configure(dialect=DefaultDialect())
    return AutogenContext(migration_context, opts=opts)


class _RecordingTransaction:
    """Stands in for a SQLAlchemy Transaction, recording boundaries."""

    def __init__(self, connection):
        self.connection = connection

    def commit(self):
        self.connection.log.append(("commit", self.connection.tag))
        self.connection.transaction = None

    def rollback(self):
        self.connection.log.append(("rollback", self.connection.tag))
        self.connection.transaction = None

    def __exit__(self, type_, value, traceback):
        if type_ is None:
            self.commit()
        else:
            self.rollback()
        return False


class _RecordingConnection:
    """A connection double that records transaction and isolation
    level changes instead of talking to a database."""

    def __init__(
        self,
        dialect,
        log,
        isolation_level="READ COMMITTED",
        tag="base",
        fail_on=None,
    ):
        self.dialect = dialect
        self.log = log
        self.isolation_level = isolation_level
        self.tag = tag
        self.fail_on = fail_on
        self.transaction = None

    def in_transaction(self):
        return self.transaction is not None

    def get_transaction(self):
        return self.transaction

    def begin(self):
        self.log.append(("begin", self.tag, self.isolation_level))
        self.transaction = _RecordingTransaction(self)
        return self.transaction

    def get_isolation_level(self):
        self.log.append(("get_isolation_level", self.tag))
        return self.isolation_level

    def execution_options(self, **kw):
        isolation_level = kw.get("isolation_level", self.isolation_level)
        self.log.append(("execution_options", self.tag, isolation_level))
        return _RecordingConnection(
            self.dialect,
            self.log,
            isolation_level=isolation_level,
            tag="autocommit" if isolation_level == "AUTOCOMMIT" else self.tag,
            fail_on=self.fail_on,
        )

    def execute(self, clause, params=None):
        if isinstance(clause, str):
            clause = text(clause)
        compiled = str(clause.compile(dialect=self.dialect))
        self.log.append(("exec", self.tag, compiled))
        if self.fail_on is not None and self.fail_on in compiled:
            raise Exception("database error on: %s" % compiled)


class RenderAutocommitOpTest(TestBase):
    def test_render_group(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[
                ops.CreateTableOp(
                    "t1", [sa.Column("id", sa.Integer, primary_key=True)]
                ),
                ops.AutocommitOp(
                    [
                        ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'"),
                        ops.CreateIndexOp("ix_t1_id", "t1", ["id"]),
                    ]
                ),
                ops.DropTableOp("t2"),
            ]
        )

        eq_(
            autogenerate.render_python_code(upgrade_ops),
            "# ### commands auto generated by Alembic - please adjust! ###\n"
            "    op.create_table('t1',\n"
            "    sa.Column('id', sa.Integer(), nullable=False),\n"
            "    sa.PrimaryKeyConstraint('id')\n"
            "    )\n"
            "    with op.get_context().autocommit_block():\n"
            "        op.execute(\"ALTER TYPE mood ADD VALUE 'soso'\")\n"
            "        op.create_index('ix_t1_id', 't1', ['id'], unique=False)\n"
            "\n"
            "    op.drop_table('t2')\n"
            "    # ### end Alembic commands ###",
        )

    def test_default_rendering_unchanged(self):
        # the same operations without an AutocommitOp group must not
        # emit any autocommit construct
        upgrade_ops = ops.UpgradeOps(
            ops=[
                ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'"),
                ops.CreateIndexOp("ix_t1_id", "t1", ["id"]),
            ]
        )
        code = autogenerate.render_python_code(upgrade_ops)
        assert "autocommit_block" not in code
        eq_(
            code,
            "# ### commands auto generated by Alembic - please adjust! ###\n"
            "    op.execute(\"ALTER TYPE mood ADD VALUE 'soso'\")\n"
            "    op.create_index('ix_t1_id', 't1', ['id'], unique=False)\n"
            "    # ### end Alembic commands ###",
        )

    def test_render_empty_group(self):
        code = autogenerate.render_python_code(
            ops.UpgradeOps(ops=[ops.AutocommitOp([])])
        )
        eq_(
            code,
            "# ### commands auto generated by Alembic - please adjust! ###\n"
            "    with op.get_context().autocommit_block():\n"
            "        pass\n"
            "\n"
            "    # ### end Alembic commands ###",
        )
        compile("def upgrade():\n" + code + "\n", "revision.py", "exec")

    def test_reverse_group(self):
        group = ops.AutocommitOp(
            [
                ops.CreateIndexOp("ix_t1_id", "t1", ["id"]),
                ops.AddColumnOp("t1", sa.Column("c1", sa.Integer)),
            ]
        )
        reversed_group = group.reverse()

        assert isinstance(reversed_group, ops.AutocommitOp)
        eq_(
            [type(sub_op) for sub_op in reversed_group.ops],
            [ops.DropColumnOp, ops.DropIndexOp],
        )

        eq_(
            autogenerate.render_python_code(ops.DowngradeOps(ops=[group])),
            "# ### commands auto generated by Alembic - please adjust! ###\n"
            "    with op.get_context().autocommit_block():\n"
            "        op.create_index('ix_t1_id', 't1', ['id'], unique=False)\n"
            "        op.add_column('t1', sa.Column('c1', sa.Integer(), "
            "nullable=True))\n"
            "\n"
            "    # ### end Alembic commands ###",
        )

    def test_reverse_irreversible_sub_op_raises(self):
        group = ops.AutocommitOp(
            [
                ops.CreateIndexOp("ix_t1_id", "t1", ["id"]),
                ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'"),
            ]
        )
        assert_raises_message(
            CommandError,
            "Cannot produce a downgrade for this AutocommitOp group",
            group.reverse,
        )

    def test_nested_group_rejected(self):
        assert_raises_message(
            CommandError,
            "AutocommitOp groups cannot be nested",
            ops.AutocommitOp,
            [ops.AutocommitOp([ops.CreateIndexOp("ix", "t1", ["id"])])],
        )

    def test_nested_group_rejected_on_render(self):
        # groups mutated after construction are still rejected at
        # render time
        group = ops.AutocommitOp([ops.CreateIndexOp("ix", "t1", ["id"])])
        group.ops.append(ops.AutocommitOp([]))
        assert_raises_message(
            CommandError,
            "AutocommitOp groups cannot be nested",
            autogenerate.render_python_code,
            ops.UpgradeOps(ops=[group]),
        )

    def test_modify_table_ops_inside_group_rejected(self):
        assert_raises_message(
            CommandError,
            "AutocommitOp groups cannot contain ModifyTableOps",
            ops.AutocommitOp,
            [ops.ModifyTableOps("t1", ops=[ops.DropColumnOp("t1", "c")])],
        )

    def test_group_inside_batch_render_rejected(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[
                ops.ModifyTableOps(
                    "t1",
                    ops=[
                        ops.AutocommitOp(
                            [ops.CreateIndexOp("ix", "t1", ["id"])]
                        )
                    ],
                )
            ]
        )
        assert_raises_message(
            CommandError,
            "AutocommitOp groups cannot be rendered within a "
            "batch_alter_table",
            autogenerate.render_python_code,
            upgrade_ops,
            render_as_batch=True,
        )

    def test_render_multi_engine(self):
        migration_script = ops.MigrationScript(
            "abc123",
            ops.UpgradeOps(
                ops=[
                    ops.AutocommitOp(
                        [ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'x'")]
                    )
                ],
                upgrade_token="engine1_upgrades",
            ),
            ops.DowngradeOps(
                ops=[ops.CreateIndexOp("ix1", "t1", ["id"])],
                downgrade_token="engine1_downgrades",
            ),
        )
        migration_script.upgrade_ops_list.append(
            ops.UpgradeOps(
                ops=[
                    ops.AutocommitOp(
                        [ops.ExecuteSQLOp("ALTER TYPE other ADD VALUE 'y'")]
                    )
                ],
                upgrade_token="engine2_upgrades",
            )
        )
        migration_script.downgrade_ops_list.append(
            ops.DowngradeOps(
                ops=[ops.CreateIndexOp("ix2", "t2", ["id"])],
                downgrade_token="engine2_downgrades",
            )
        )

        autogen_context = _autogen_context()
        template_args: dict = {}
        autogen_render._render_python_into_templatevars(
            autogen_context, migration_script, template_args
        )

        eq_(
            template_args["engine1_upgrades"],
            "# ### commands auto generated by Alembic - please adjust! ###\n"
            "    with op.get_context().autocommit_block():\n"
            "        op.execute(\"ALTER TYPE mood ADD VALUE 'x'\")\n"
            "\n"
            "    # ### end Alembic commands ###",
        )
        eq_(
            template_args["engine2_upgrades"],
            "# ### commands auto generated by Alembic - please adjust! ###\n"
            "    with op.get_context().autocommit_block():\n"
            "        op.execute(\"ALTER TYPE other ADD VALUE 'y'\")\n"
            "\n"
            "    # ### end Alembic commands ###",
        )
        # non-autocommit tokens render normally
        eq_(
            template_args["engine1_downgrades"],
            "# ### commands auto generated by Alembic - please adjust! ###\n"
            "    op.create_index('ix1', 't1', ['id'], unique=False)\n"
            "    # ### end Alembic commands ###",
        )

    def test_reload_and_execute_generated_code(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[
                ops.CreateIndexOp("ix_before", "t1", ["id"]),
                ops.AutocommitOp(
                    [
                        ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'"),
                        ops.ExecuteSQLOp("VACUUM ANALYZE t1"),
                    ]
                ),
                ops.CreateIndexOp("ix_after", "t1", ["c1"]),
            ]
        )
        rendered = autogenerate.render_python_code(upgrade_ops)
        source = (
            "from alembic import op\n"
            "import sqlalchemy as sa\n"
            "\n"
            "def upgrade():\n"
            f"{rendered}\n"
        )

        namespace: dict = {}
        exec(compile(source, "revision.py", "exec"), namespace)

        log: list = []
        conn = _RecordingConnection(postgresql.dialect(), log)
        context = MigrationContext.configure(connection=conn)
        with Operations.context(context):
            with context.begin_transaction():
                namespace["upgrade"]()

        eq_(
            log,
            [
                ("begin", "base", "READ COMMITTED"),
                ("exec", "base", "CREATE INDEX ix_before ON t1 (id)"),
                ("commit", "base"),
                ("get_isolation_level", "base"),
                ("execution_options", "base", "AUTOCOMMIT"),
                ("begin", "autocommit", "AUTOCOMMIT"),
                ("exec", "autocommit", "ALTER TYPE mood ADD VALUE 'soso'"),
                ("exec", "autocommit", "VACUUM ANALYZE t1"),
                ("commit", "autocommit"),
                ("execution_options", "autocommit", "READ COMMITTED"),
                ("begin", "base", "READ COMMITTED"),
                ("exec", "base", "CREATE INDEX ix_after ON t1 (c1)"),
                ("commit", "base"),
            ],
        )


class OnlineAutocommitOpTest(TestBase):
    def _context(self, log, **kw):
        conn = _RecordingConnection(postgresql.dialect(), log, **kw)
        return MigrationContext.configure(connection=conn)

    def test_isolation_level_recovery(self):
        log: list = []
        context = self._context(log)
        with Operations.context(context):
            with context.begin_transaction():
                op.execute("SELECT 1")
                op.invoke(
                    ops.AutocommitOp(
                        [ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'")]
                    )
                )
                op.execute("SELECT 2")

        eq_(
            log,
            [
                ("begin", "base", "READ COMMITTED"),
                ("exec", "base", "SELECT 1"),
                ("commit", "base"),
                ("get_isolation_level", "base"),
                ("execution_options", "base", "AUTOCOMMIT"),
                ("begin", "autocommit", "AUTOCOMMIT"),
                ("exec", "autocommit", "ALTER TYPE mood ADD VALUE 'soso'"),
                ("commit", "autocommit"),
                ("execution_options", "autocommit", "READ COMMITTED"),
                ("begin", "base", "READ COMMITTED"),
                ("exec", "base", "SELECT 2"),
                ("commit", "base"),
            ],
        )

    def test_isolation_level_recovery_on_error(self):
        log: list = []
        context = self._context(log, fail_on="FAILING")
        with Operations.context(context):
            with expect_raises_message(Exception, "database error on"):
                with context.begin_transaction():
                    op.execute("SELECT 1")
                    op.invoke(
                        ops.AutocommitOp(
                            [
                                ops.ExecuteSQLOp("SELECT FAILING"),
                                ops.ExecuteSQLOp("SELECT never_reached"),
                            ]
                        )
                    )

        # the failing statement aborts the group; the isolation level
        # is still restored and the outer transaction is re-established
        # before being rolled back by the outer context manager
        eq_(
            log,
            [
                ("begin", "base", "READ COMMITTED"),
                ("exec", "base", "SELECT 1"),
                ("commit", "base"),
                ("get_isolation_level", "base"),
                ("execution_options", "base", "AUTOCOMMIT"),
                ("begin", "autocommit", "AUTOCOMMIT"),
                ("exec", "autocommit", "SELECT FAILING"),
                ("commit", "autocommit"),
                ("execution_options", "autocommit", "READ COMMITTED"),
                ("begin", "base", "READ COMMITTED"),
                ("rollback", "base"),
            ],
        )

    def test_group_within_batch_rejected(self):
        context = op_fixture("postgresql")
        with op.batch_alter_table("t1") as batch_op:
            assert_raises_message(
                CommandError,
                "AutocommitOp groups cannot be invoked within a "
                "batch_alter_table",
                batch_op.invoke,
                ops.AutocommitOp([ops.ExecuteSQLOp("SELECT 1")]),
            )


class OfflineAutocommitOpTest(TestBase):
    def test_offline_pg_transaction_boundaries(self):
        context = op_fixture("postgresql", as_sql=True)
        op.execute("SELECT 1")
        op.invoke(
            ops.AutocommitOp(
                [
                    ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'"),
                    ops.CreateIndexOp("ix_t1_id", "t1", ["id"]),
                ]
            )
        )
        op.execute("SELECT 2")

        context.assert_(
            "SELECT 1",
            "COMMIT",
            "ALTER TYPE mood ADD VALUE 'soso'",
            "CREATE INDEX ix_t1_id ON t1 (id)",
            "BEGIN",
            "SELECT 2",
        )

    def test_offline_pg_reload_generated_code(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[
                ops.AutocommitOp(
                    [ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'")]
                ),
            ]
        )
        rendered = autogenerate.render_python_code(upgrade_ops)
        source = (
            "from alembic import op\n"
            "import sqlalchemy as sa\n"
            "\n"
            "def upgrade():\n"
            f"{rendered}\n"
        )
        namespace: dict = {}
        exec(compile(source, "revision.py", "exec"), namespace)

        context = op_fixture("postgresql", as_sql=True)
        namespace["upgrade"]()

        context.assert_(
            "COMMIT",
            "ALTER TYPE mood ADD VALUE 'soso'",
            "BEGIN",
        )
