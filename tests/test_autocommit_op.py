def _table_op(name="t1"):
    return ops.CreateTableOp(name, [sa.Column("x", sa.Integer)])


class AutocommitOpRenderTest(TestBase):
    def test_render_group_preserves_order(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[
                _table_op("t1"),
                ops.AutocommitOp(
                    ops=[
                        ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'"),
                        ops.CreateIndexOp("ix_t1_x", "t1", ["x"]),
                    ]
                ),
                _table_op("t2"),
            ]
        )
        eq_(
            render_python_code(upgrade_ops),
            "# ### commands auto generated by Alembic - please adjust! ###\n"
            "    op.create_table('t1',\n"
            "    sa.Column('x', sa.Integer(), nullable=True)\n"
            "    )\n"
            "    with op.autocommit_block():\n"
            "        op.execute(\"ALTER TYPE mood ADD VALUE 'soso'\")\n"
            "        op.create_index('ix_t1_x', 't1', ['x'], unique=False)\n"
            "\n"
            "    op.create_table('t2',\n"
            "    sa.Column('x', sa.Integer(), nullable=True)\n"
            "    )\n"
            "    # ### end Alembic commands ###",
        )

    def test_render_reversed_group(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[
                ops.AutocommitOp(
                    ops=[
                        _table_op("t1"),
                        ops.CreateIndexOp("ix_t1_x", "t1", ["x"]),
                    ]
                ),
            ]
        )
        eq_(
            render_python_code(upgrade_ops.reverse()),
            "# ### commands auto generated by Alembic - please adjust! ###\n"
            "    with op.autocommit_block():\n"
            "        op.drop_index('ix_t1_x', table_name='t1')\n"
            "        op.drop_table('t1')\n"
            "\n"
            "    # ### end Alembic commands ###",
        )

    def test_render_empty_group_renders_nothing(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[_table_op("t1"), ops.AutocommitOp(), _table_op("t2")]
        )
        eq_(
            render_python_code(upgrade_ops),
            render_python_code(
                ops.UpgradeOps(ops=[_table_op("t1"), _table_op("t2")])
            ),
        )

    def test_reverse_group_reverses_sub_ops(self):
        group = ops.AutocommitOp(
            ops=[_table_op("t1"), ops.CreateIndexOp("ix_t1_x", "t1", ["x"])]
        )
        reversed_group = group.reverse()
        assert isinstance(reversed_group, ops.AutocommitOp)
        eq_(len(reversed_group.ops), 2)
        assert isinstance(reversed_group.ops[0], ops.DropIndexOp)
        assert isinstance(reversed_group.ops[1], ops.DropTableOp)

    def test_reverse_irreversible_sub_op_raises(self):
        group = ops.AutocommitOp(ops=[ops.ExecuteSQLOp("SELECT 1")])
        with expect_raises_message(Exception, "is not reversible"):
            group.reverse()

    def test_nested_group_rejected_at_construction(self):
        with expect_raises_message(
            Exception, "AutocommitOp groups cannot be nested"
        ):
            ops.AutocommitOp(ops=[ops.AutocommitOp(ops=[_table_op()])])

    def test_nested_group_rejected_at_render(self):
        group = ops.AutocommitOp(ops=[_table_op()])
        group.ops.append(ops.AutocommitOp(ops=[_table_op("t2")]))
        with expect_raises_message(
            Exception, "AutocommitOp groups cannot be nested"
        ):
            render_python_code(ops.UpgradeOps(ops=[group]))

    def test_group_inside_batch_render_rejected(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[
                ops.ModifyTableOps(
                    "t1",
                    [
                        ops.AutocommitOp(
                            ops=[
                                ops.AddColumnOp.from_column_and_tablename(
                                    None, "t1", sa.Column("y", sa.Integer)
                                )
                            ]
                        )
                    ],
                )
            ]
        )
        with expect_raises_message(
            Exception,
            "AutocommitOp cannot be rendered inside of a "
            "batch_alter_table block",
        ):
            render_python_code(upgrade_ops, render_as_batch=True)

    def test_batch_inside_group_render_rejected(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[
                ops.AutocommitOp(
                    ops=[
                        ops.ModifyTableOps(
                            "t1",
                            [
                                ops.AddColumnOp.from_column_and_tablename(
                                    None, "t1", sa.Column("y", sa.Integer)
                                )
                            ],
                        )
                    ]
                )
            ]
        )
        with expect_raises_message(
            Exception,
            "AutocommitOp cannot contain operations that render "
            "as a batch_alter_table block",
        ):
            render_python_code(upgrade_ops, render_as_batch=True)

    def test_multi_engine_render(self):
        migration_context = MigrationContext.configure(
            dialect=DefaultDialect()
        )
        autogen_context = AutogenContext(
            migration_context,
            opts={
                "sqlalchemy_module_prefix": "sa.",
                "alembic_module_prefix": "op.",
                "render_item": None,
                "render_as_batch": False,
                "user_module_prefix": None,
            },
        )
        script = ops.MigrationScript(
            rev_id=None,
            upgrade_ops=[
                ops.UpgradeOps(
                    [
                        ops.AutocommitOp(
                            ops=[
                                ops.ExecuteSQLOp("ALTER TYPE t ADD VALUE 'a'")
                            ]
                        )
                    ],
                    upgrade_token="upgrades",
                ),
                ops.UpgradeOps(
                    [
                        _table_op("t1"),
                        ops.AutocommitOp(
                            ops=[
                                ops.ExecuteSQLOp("ALTER TYPE t ADD VALUE 'b'")
                            ]
                        ),
                    ],
                    upgrade_token="upgrades_engine2",
                ),
            ],
            downgrade_ops=[
                ops.DowngradeOps([], downgrade_token="downgrades"),
                ops.DowngradeOps([], downgrade_token="downgrades_engine2"),
            ],
        )
        template_args: dict = {}
        autogen_render._render_python_into_templatevars(
            autogen_context, script, template_args
        )
        for token in ("upgrades", "upgrades_engine2"):
            assert (
                "with op.autocommit_block():" in template_args[token]
            ), template_args[token]
        assert "ALTER TYPE t ADD VALUE 'a'" in template_args["upgrades"]
        assert (
            "ALTER TYPE t ADD VALUE 'b'" in template_args["upgrades_engine2"]
        )


class AutocommitOpOfflineTest(TestBase):
    def test_offline_transaction_boundaries(self):
        context = op_fixture("postgresql", as_sql=True)

        op.execute("step 1")
        op.invoke(
            ops.AutocommitOp(
                ops=[
                    ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'"),
                    ops.ExecuteSQLOp("CREATE INDEX ix_t ON t (x)"),
                ]
            )
        )
        op.execute("step 2")

        eq_(
            context.get_buf().lines,
            [
                "step 1",
                "COMMIT",
                "ALTER TYPE mood ADD VALUE 'soso'",
                "CREATE INDEX ix_t ON t (x)",
                "BEGIN",
                "step 2",
            ],
        )

    def test_reload_and_execute_rendered_revision(self):
        upgrade_ops = ops.UpgradeOps(
            ops=[
                ops.ExecuteSQLOp("step 1"),
                ops.AutocommitOp(
                    ops=[
                        ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'"),
                        ops.ExecuteSQLOp("CREATE INDEX ix_t ON t (x)"),
                    ]
                ),
                ops.ExecuteSQLOp("step 2"),
            ]
        )
        code = render_python_code(upgrade_ops)
        module_code = "def upgrade():\n%s\n" % code

        context = op_fixture("postgresql", as_sql=True)
        namespace = {"op": op}
        exec(module_code, namespace)
        namespace["upgrade"]()

        eq_(
            context.get_buf().lines,
            [
                "step 1",
                "COMMIT",
                "ALTER TYPE mood ADD VALUE 'soso'",
                "CREATE INDEX ix_t ON t (x)",
                "BEGIN",
                "step 2",
            ],
        )

    def test_offline_nested_group_rejected_at_invoke(self):
        op_fixture("postgresql", as_sql=True)
        group = ops.AutocommitOp(ops=[ops.ExecuteSQLOp("step 1")])
        group.ops.append(ops.AutocommitOp(ops=[ops.ExecuteSQLOp("step 2")]))
        with expect_raises_message(
            Exception, "AutocommitOp groups cannot be nested"
        ):
            op.invoke(group)


class _RecordingTransaction:
    def __init__(self, conn):
        self.conn = conn

    def commit(self):
        self.conn.log.append("commit")
        self.conn._transaction = None

    def rollback(self):
        self.conn.log.append("rollback")
        self.conn._transaction = None

    def __enter__(self):
        return self

    def __exit__(self, type_, value, traceback):
        if type_ is None:
            self.commit()
        else:
            self.rollback()


class _RecordingConnection:
    """A connection double that records transaction and isolation
    level changes."""

    def __init__(self):
        self.dialect = postgresql.dialect()
        self.log = []
        self.isolation_level = "READ COMMITTED"
        self._transaction = None

    def get_isolation_level(self):
        return self.isolation_level

    def execution_options(self, **opt):
        if "isolation_level" in opt:
            self.log.append("isolation_level=%s" % opt["isolation_level"])
            self.isolation_level = opt["isolation_level"]
        return self

    def begin(self):
        self.log.append("begin")
        self._transaction = _RecordingTransaction(self)
        return self._transaction

    def get_transaction(self):
        return self._transaction

    def in_transaction(self):
        return self._transaction is not None

    def execute(self, clause, *args, **kw):
        if isinstance(clause, str):
            clause = sa.text(clause)
        self.log.append(
            "execute: %s" % str(clause.compile(dialect=self.dialect))
        )


class _FailingOp(MigrateOperation):
    def reverse(self):
        raise NotImplementedError


@Operations.implementation_for(_FailingOp)
def _failing_op(operations, operation):
    raise Exception("database error")


class AutocommitOpOnlineTest(TestBase):
    def _fixture(self):
        conn = _RecordingConnection()
        context = MigrationContext.configure(connection=conn)
        return conn, context, Operations(context)

    def test_online_commit_and_isolation_restore(self):
        conn, context, operations = self._fixture()

        with context.begin_transaction():
            context.execute("step 1")
            operations.invoke(
                ops.AutocommitOp(
                    ops=[
                        ops.ExecuteSQLOp("ALTER TYPE mood ADD VALUE 'soso'"),
                        ops.ExecuteSQLOp("CREATE INDEX ix_t ON t (x)"),
                    ]
                )
            )
            context.execute("step 2")

        eq_(
            conn.log,
            [
                "begin",
                "execute: step 1",
                # entering the autocommit block commits the
                # preceding transaction
                "commit",
                "isolation_level=AUTOCOMMIT",
                "begin",
                "execute: ALTER TYPE mood ADD VALUE 'soso'",
                "execute: CREATE INDEX ix_t ON t (x)",
                # leaving the block restores the previous isolation
                # level and restarts a transaction
                "commit",
                "isolation_level=READ COMMITTED",
                "begin",
                "execute: step 2",
                "commit",
            ],
        )
        eq_(conn.isolation_level, "READ COMMITTED")
        eq_(conn._transaction, None)

    def test_online_exception_restores_isolation(self):
        conn, context, operations = self._fixture()

        def go():
            with context.begin_transaction():
                context.execute("step 1")
                operations.invoke(
                    ops.AutocommitOp(
                        ops=[
                            ops.ExecuteSQLOp(
                                "ALTER TYPE mood ADD VALUE 'soso'"
                            ),
                            _FailingOp(),
                            ops.ExecuteSQLOp("never runs"),
                        ]
                    )
                )

        assert_raises_message(Exception, "database error", go)

        eq_(
            conn.log,
            [
                "begin",
                "execute: step 1",
                "commit",
                "isolation_level=AUTOCOMMIT",
                "begin",
                "execute: ALTER TYPE mood ADD VALUE 'soso'",
                # even though the group failed, the isolation level is
                # restored and the outer transaction is restarted
                "commit",
                "isolation_level=READ COMMITTED",
                "begin",
                "rollback",
            ],
        )
        eq_(conn.isolation_level, "READ COMMITTED")
        eq_(conn._transaction, None)

    def test_online_no_transaction(self):
        conn, context, operations = self._fixture()

        operations.invoke(ops.AutocommitOp(ops=[ops.ExecuteSQLOp("SELECT 1")]))

        eq_(
            conn.log,
            [
                "isolation_level=AUTOCOMMIT",
                "begin",
                "execute: SELECT 1",
                "commit",
                "isolation_level=READ COMMITTED",
            ],
        )

    def test_invoke_inside_batch_rejected(self):
        op_fixture("postgresql")
        with op.batch_alter_table("t1") as batch_op:
            with expect_raises_message(
                Exception,
                "AutocommitOp cannot be invoked inside of a "
                "batch_alter_table block",
            ):
                batch_op.invoke(
                    ops.AutocommitOp(ops=[ops.ExecuteSQLOp("SELECT 1")])
                )
