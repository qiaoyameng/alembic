class ColumnRenameCompareTest(TestBase):
    def setUp(self):
        self._conns = []
        self.engine = create_engine("sqlite://")
        _db_metadata().create_all(self.engine)

    def tearDown(self):
        for conn in self._conns:
            conn.close()
        self.engine.dispose()

    def _produce(self, m2, column_renames, **extra_opts):
        opts = {
            "target_metadata": m2,
            "compare_type": True,
            "compare_server_default": True,
            "column_renames": column_renames,
            "upgrade_token": "upgrades",
            "downgrade_token": "downgrades",
        }
        opts.update(extra_opts)
        conn = self.engine.connect()
        self._conns.append(conn)
        context = MigrationContext.configure(connection=conn, opts=opts)
        return context, produce_migrations(context, m2)

    def _alter_column_ops(self, migration_script):
        return [
            op_
            for op_ in migration_script.upgrade_ops.ops[0].ops
            if isinstance(op_, ops.AlterColumnOp)
        ]

    def test_rename_detected_as_alter_column(self):
        context, script = self._produce(
            _model_metadata(), {(None, "t"): {"old_col": "new_col"}}
        )
        (modify_table_op,) = script.upgrade_ops.ops
        (alter_op,) = modify_table_op.ops
        assert isinstance(alter_op, ops.AlterColumnOp)
        eq_(alter_op.column_name, "old_col")
        eq_(alter_op.modify_name, "new_col")
        eq_(alter_op.modify_type, None)

        # no drop_column / add_column pair
        eq_(len(script.upgrade_ops.ops), 1)

    def test_rename_diff_tuple(self):
        context, script = self._produce(
            _model_metadata(), {(None, "t"): {"old_col": "new_col"}}
        )
        diffs = compare_metadata(context, _model_metadata())
        eq_(
            diffs,
            [[("rename_column", None, "t", "old_col", "new_col")]],
        )

    def test_rename_and_type_change(self):
        m2 = MetaData()
        Table(
            "t",
            m2,
            Column("id", Integer, primary_key=True),
            Column("new_col", String(100), nullable=False),
            Column("other", Integer),
        )
        context, script = self._produce(
            m2, {(None, "t"): {"old_col": "new_col"}}
        )
        (alter_op,) = self._alter_column_ops(script)
        eq_(alter_op.column_name, "old_col")
        eq_(alter_op.modify_name, "new_col")
        assert isinstance(alter_op.modify_type, String)
        eq_(alter_op.modify_type.length, 100)
        eq_(alter_op.modify_nullable, False)

    def test_render_upgrade_and_downgrade(self):
        context, script = self._produce(
            _model_metadata(), {(None, "t"): {"old_col": "new_col"}}
        )
        eq_(
            render_python_code(script.upgrade_ops, migration_context=context),
            "# ### commands auto generated by Alembic - please adjust! "
            "###\n"
            "    op.alter_column('t', 'old_col',\n"
            "               existing_type=sa.VARCHAR(length=50),\n"
            "               new_column_name='new_col',\n"
            "               existing_nullable=True)\n"
            "    # ### end Alembic commands ###",
        )
        eq_(
            render_python_code(
                script.downgrade_ops, migration_context=context
            ),
            "# ### commands auto generated by Alembic - please adjust! "
            "###\n"
            "    op.alter_column('t', 'new_col',\n"
            "               existing_type=sa.VARCHAR(length=50),\n"
            "               new_column_name='old_col',\n"
            "               existing_nullable=True)\n"
            "    # ### end Alembic commands ###",
        )

    def test_render_as_batch(self):
        context, script = self._produce(
            _model_metadata(),
            {(None, "t"): {"old_col": "new_col"}},
            render_as_batch=True,
        )
        eq_(
            render_python_code(
                script.upgrade_ops,
                render_as_batch=True,
                migration_context=context,
            ),
            "# ### commands auto generated by Alembic - please adjust! "
            "###\n"
            "    with op.batch_alter_table('t', schema=None) as batch_op:\n"
            "        batch_op.alter_column('old_col',\n"
            "               existing_type=sa.VARCHAR(length=50),\n"
            "               new_column_name='new_col',\n"
            "               existing_nullable=True)\n"
            "\n"
            "    # ### end Alembic commands ###",
        )

    def test_rename_in_composite_constraint_and_index(self):
        m1 = MetaData()
        t1 = Table(
            "t",
            m1,
            Column("id", Integer, primary_key=True),
            Column("old_col", String(50)),
            Column("other", Integer),
            UniqueConstraint("old_col", "other", name="uq_t"),
        )
        Index("ix_t", t1.c.old_col, t1.c.other)
        self.engine.dispose()
        self.engine = create_engine("sqlite://")
        m1.create_all(self.engine)

        m2 = MetaData()
        t2 = Table(
            "t",
            m2,
            Column("id", Integer, primary_key=True),
            Column("new_col", String(50)),
            Column("other", Integer),
            UniqueConstraint("new_col", "other", name="uq_t"),
        )
        Index("ix_t", t2.c.new_col, t2.c.other)

        context, script = self._produce(
            m2, {(None, "t"): {"old_col": "new_col"}}
        )
        (modify_table_op,) = script.upgrade_ops.ops
        # only the rename; the constraint and index follow the rename
        # and are not dropped / re-added
        eq_(len(modify_table_op.ops), 1)
        (alter_op,) = modify_table_op.ops
        eq_(alter_op.modify_name, "new_col")

    def test_no_hints_produces_drop_and_add(self):
        context, script = self._produce(_model_metadata(), None)
        flat = script.upgrade_ops.ops[0].ops
        eq_(
            {type(o) for o in flat},
            {ops.AddColumnOp, ops.DropColumnOp},
        )

    def test_rename_in_composite_foreign_key(self):
        from sqlalchemy import ForeignKeyConstraint

        self.engine.dispose()
        self.engine = create_engine("sqlite://")
        with self.engine.begin() as conn:
            conn.execute(
                text(
                    "CREATE TABLE p (a INTEGER, b INTEGER, "
                    "PRIMARY KEY (a, b))"
                )
            )
            conn.execute(
                text(
                    "CREATE TABLE c (x_old INTEGER, y INTEGER, "
                    "FOREIGN KEY(x_old, y) REFERENCES p(a, b))"
                )
            )

        m2 = MetaData()
        Table(
            "p",
            m2,
            Column("a", Integer, primary_key=True),
            Column("b", Integer, primary_key=True),
        )
        c = Table(
            "c",
            m2,
            Column("x_new", Integer),
            Column("y", Integer),
        )
        c.append_constraint(
            ForeignKeyConstraint(["x_new", "y"], ["p.a", "p.b"])
        )

        opts = {
            "target_metadata": m2,
            "column_renames": {(None, "c"): {"x_old": "x_new"}},
            "upgrade_token": "upgrades",
            "downgrade_token": "downgrades",
        }
        conn = self.engine.connect()
        self._conns.append(conn)
        context = MigrationContext.configure(connection=conn, opts=opts)
        script = produce_migrations(context, m2)

        remaining = []
        for top in script.upgrade_ops.ops:
            remaining.extend(_no_pk_noise(top.ops))
        # only the rename; the composite FK follows the rename and
        # is not dropped / re-added
        eq_(len(remaining), 1)
        (alter_op,) = remaining
        eq_(alter_op.column_name, "x_old")
        eq_(alter_op.modify_name, "x_new")

    def test_include_object_excludes_column(self):
        def include_object(object, name, type_, reflected, compare_to):
            return not (type_ == "column" and name in ("old_col", "new_col"))

        context, script = self._produce(
            _model_metadata(),
            {(None, "t"): {"old_col": "new_col"}},
            include_object=include_object,
        )
        # the filtered columns are not pulled back by the hint;
        # nothing is generated at all
        eq_(script.upgrade_ops.ops, [])

    def test_include_name_excludes_column(self):
        def include_name(name, type_, parent_names):
            return not (type_ == "column" and name == "old_col")

        context, script = self._produce(
            _model_metadata(),
            {(None, "t"): {"old_col": "new_col"}},
            include_name=include_name,
        )
        # the reflected column is filtered, so the rename is not
        # applied; the metadata-side column is added as usual for
        # include_name, which only filters reflected objects
        (modify_table_op,) = script.upgrade_ops.ops
        eq_(len(modify_table_op.ops), 1)
        (add_op,) = modify_table_op.ops
        assert isinstance(add_op, ops.AddColumnOp)
        eq_(add_op.column.name, "new_col")

    def test_two_schemas_same_table_name(self):
        m2 = MetaData()
        Table(
            "t",
            m2,
            Column("id", Integer, primary_key=True),
            Column("new_main", String(50)),
        )
        Table(
            "t",
            m2,
            Column("id", Integer, primary_key=True),
            Column("new_other", String(50)),
            schema="other_schema",
        )

        conn = self.engine.connect()
        self._conns.append(conn)
        conn.execute(text("DROP TABLE t"))
        conn.execute(text("ATTACH DATABASE ':memory:' AS other_schema"))
        conn.execute(
            text(
                "CREATE TABLE other_schema.t ("
                "id INTEGER PRIMARY KEY, old_other VARCHAR(50))"
            )
        )
        conn.execute(
            text(
                "CREATE TABLE main.t ("
                "id INTEGER PRIMARY KEY, old_main VARCHAR(50))"
            )
        )
        conn.commit()

        opts = {
            "target_metadata": m2,
            "include_schemas": True,
            "column_renames": {
                (None, "t"): {"old_main": "new_main"},
                ("other_schema", "t"): {"old_other": "new_other"},
            },
            "upgrade_token": "upgrades",
            "downgrade_token": "downgrades",
        }
        context = MigrationContext.configure(connection=conn, opts=opts)
        script = produce_migrations(context, m2)

        renames = {}
        for top in script.upgrade_ops.ops:
            for sub in top.ops:
                if isinstance(sub, ops.AlterColumnOp) and (
                    sub.modify_name is not None
                ):
                    renames[(top.schema, top.table_name)] = (
                        sub.column_name,
                        sub.modify_name,
                    )
        eq_(
            renames,
            {
                (None, "t"): ("old_main", "new_main"),
                ("other_schema", "t"): ("old_other", "new_other"),
            },
        )


class ColumnRenameValidationTest(TestBase):
    def setUp(self):
        self._conns = []
        self.engine = create_engine("sqlite://")
        _db_metadata().create_all(self.engine)

    def tearDown(self):
        for conn in self._conns:
            conn.close()
        self.engine.dispose()

    def _expect_error(self, m2, column_renames, message, **extra_opts):
        opts = {
            "target_metadata": m2,
            "column_renames": column_renames,
            "upgrade_token": "upgrades",
            "downgrade_token": "downgrades",
        }
        opts.update(extra_opts)
        conn = self.engine.connect()
        self._conns.append(conn)
        context = MigrationContext.configure(connection=conn, opts=opts)
        assert_raises_message(
            CommandError, message, produce_migrations, context, m2
        )

    def test_old_column_not_in_database(self):
        self._expect_error(
            _model_metadata(),
            {(None, "t"): {"nonexistent": "new_col"}},
            "column 'nonexistent' does not exist in the database",
        )

    def test_new_column_not_in_metadata(self):
        self._expect_error(
            _model_metadata(),
            {(None, "t"): {"old_col": "nonexistent"}},
            "column 'nonexistent' does not exist in the target metadata",
        )

    def test_old_column_still_in_metadata(self):
        m2 = MetaData()
        Table(
            "t",
            m2,
            Column("id", Integer, primary_key=True),
            Column("old_col", String(50)),
            Column("new_col", String(50)),
            Column("other", Integer),
        )
        self._expect_error(
            m2,
            {(None, "t"): {"old_col": "new_col"}},
            "column 'old_col' is still present in the target metadata",
        )

    def test_new_column_already_in_database(self):
        m1 = MetaData()
        Table(
            "t2",
            m1,
            Column("id", Integer, primary_key=True),
            Column("old_col", String(50)),
            Column("new_col", String(50)),
        )
        m1.create_all(self.engine)
        m2 = MetaData()
        Table(
            "t2",
            m2,
            Column("id", Integer, primary_key=True),
            Column("new_col", String(50)),
        )
        self._expect_error(
            m2,
            {(None, "t2"): {"old_col": "new_col"}},
            "column 'new_col' already exists in the database",
        )

    def test_many_to_one(self):
        m2 = MetaData()
        Table(
            "t",
            m2,
            Column("id", Integer, primary_key=True),
            Column("new_col", String(50)),
        )
        self._expect_error(
            m2,
            {(None, "t"): {"old_col": "new_col", "other": "new_col"}},
            "multiple columns may not be renamed to the same target name",
        )

    def test_rename_cycle(self):
        m2 = MetaData()
        Table(
            "t",
            m2,
            Column("id", Integer, primary_key=True),
            Column("old_col", String(50)),
            Column("other", Integer),
        )
        self._expect_error(
            m2,
            {(None, "t"): {"old_col": "other", "other": "old_col"}},
            "rename cycles are not supported",
        )

    def test_table_not_in_database(self):
        self._expect_error(
            _model_metadata(),
            {(None, "no_such_table"): {"old_col": "new_col"}},
            "hint for table 'no_such_table': table does not exist in "
            "the database",
        )

    def test_table_not_in_metadata(self):
        m1 = MetaData()
        Table("t2", m1, Column("a", Integer))
        m1.create_all(self.engine)
        self._expect_error(
            _model_metadata(),
            {(None, "t2"): {"a": "b"}},
            "hint for table 't2': table is not present in the target "
            "metadata",
        )

    def test_malformed_hint(self):
        self._expect_error(
            _model_metadata(),
            {"t": {"old_col": "new_col"}},
            "column_renames keys must be",
        )

    def test_hint_for_filtered_table_is_ignored(self):
        def include_object(object, name, type_, reflected, compare_to):
            return not (type_ == "table" and name == "t")

        opts = {
            "target_metadata": _model_metadata(),
            "column_renames": {(None, "t"): {"old_col": "new_col"}},
            "include_object": include_object,
            "upgrade_token": "upgrades",
            "downgrade_token": "downgrades",
        }
        conn = self.engine.connect()
        self._conns.append(conn)
        context = MigrationContext.configure(connection=conn, opts=opts)
        script = produce_migrations(context, _model_metadata())
        eq_(script.upgrade_ops.ops, [])


class ColumnRenameOnlineBatchTest(TestBase):
    """Run a rename + retype migration online against SQLite in batch
    mode and verify data is preserved across upgrade/downgrade."""

    def setUp(self):
        self.engine = create_engine("sqlite://")
        with self.engine.begin() as conn:
            conn.execute(
                text(
                    "CREATE TABLE t (id INTEGER PRIMARY KEY, "
                    "old_col VARCHAR(50), other INTEGER, "
                    "CONSTRAINT uq_t UNIQUE (old_col, other))"
                )
            )
            conn.execute(text("INSERT INTO t VALUES (1, 'data', 5)"))

    def tearDown(self):
        self.engine.dispose()

    def _model_metadata(self):
        m = MetaData()
        Table(
            "t",
            m,
            Column("id", Integer, primary_key=True),
            Column("new_col", String(100)),
            Column("other", Integer),
            UniqueConstraint("new_col", "other", name="uq_t"),
        )
        return m

    def _render(self, context, script, direction):
        src = render_python_code(
            getattr(script, direction),
            render_as_batch=True,
            migration_context=context,
        )
        lines = [
            line
            for line in src.splitlines()
            if not line.lstrip().startswith("#")
        ]
        return textwrap.dedent("\n".join(lines))

    def test_online_batch_upgrade_downgrade(self):
        m2 = self._model_metadata()
        opts = {
            "target_metadata": m2,
            "compare_type": True,
            "column_renames": {(None, "t"): {"old_col": "new_col"}},
            "render_as_batch": True,
            "upgrade_token": "upgrades",
            "downgrade_token": "downgrades",
        }
        with self.engine.connect() as conn:
            context = MigrationContext.configure(connection=conn, opts=opts)
            script = produce_migrations(context, m2)
            upgrade_src = self._render(context, script, "upgrade_ops")
            downgrade_src = self._render(context, script, "downgrade_ops")

            with Operations.context(context):
                exec(upgrade_src, {"op": op, "sa": sa})

            eq_(
                conn.exec_driver_sql("SELECT * FROM t").fetchall(),
                [(1, "data", 5)],
            )
            eq_(
                [c["name"] for c in inspect(conn).get_columns("t")],
                ["id", "new_col", "other"],
            )
            eq_(
                [str(c["type"]) for c in inspect(conn).get_columns("t")],
                ["INTEGER", "VARCHAR(100)", "INTEGER"],
            )
            eq_(
                inspect(conn).get_unique_constraints("t"),
                [{"name": "uq_t", "column_names": ["new_col", "other"]}],
            )

            # after the migration, autogenerate without the hints
            # produces nothing
            no_hint_opts = {
                k: v for k, v in opts.items() if k != "column_renames"
            }
            context2 = MigrationContext.configure(
                connection=conn, opts=no_hint_opts
            )
            script2 = produce_migrations(context2, m2)
            eq_(script2.upgrade_ops.ops, [])

            with Operations.context(context):
                exec(downgrade_src, {"op": op, "sa": sa})

            eq_(
                conn.exec_driver_sql("SELECT * FROM t").fetchall(),
                [(1, "data", 5)],
            )
            eq_(
                [c["name"] for c in inspect(conn).get_columns("t")],
                ["id", "old_col", "other"],
            )
            eq_(
                [str(c["type"]) for c in inspect(conn).get_columns("t")],
                ["INTEGER", "VARCHAR(50)", "INTEGER"],
            )
            eq_(
                inspect(conn).get_unique_constraints("t"),
                [{"name": "uq_t", "column_names": ["old_col", "other"]}],
            )
