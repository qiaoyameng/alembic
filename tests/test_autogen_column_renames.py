def _no_pk_noise(ops_):
    # sqlite reflects INTEGER PRIMARY KEY columns in a way that
    # produces nullable/autoincrement noise; filter those out
    return [
        op_
        for op_ in ops_
        if not (isinstance(op_, ops.AlterColumnOp) and op_.modify_name is None)
    ]


